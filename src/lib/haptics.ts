/**
 * Тактильный отклик (вибрация) на ключевых действиях.
 *
 * На Android короткая вибрация реально снижает число «я нажал или нет?»:
 * чек-лист выдачи библиотекарь отмечает подряд, не глядя в список.
 * iOS игнорирует navigator.vibrate (в Safari API недоступен), поэтому
 * вызов всегда обёрнут в «есть ли метод» — на iPhone это no-op без ошибок.
 */
export function tap(pattern: number | number[] = 8) {
  try {
    navigator.vibrate?.(pattern);
  } catch {
    // some WebView builds бросают на вызов — отклик не критичен
  }
}
